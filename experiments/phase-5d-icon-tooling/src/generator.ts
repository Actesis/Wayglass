import { createHash } from 'node:crypto';

import type { IconRecord } from './model.js';
import { validateIconCatalog } from './model.js';

export const generatedArtifactNames = [
  'runtime-catalog.ts',
  'source-manifest.json',
  'output-manifest.json',
] as const;

export type GeneratedArtifactName = (typeof generatedArtifactNames)[number];
export type GeneratedIconArtifacts = Readonly<Record<GeneratedArtifactName, string>>;

export interface ArtifactDrift {
  readonly artifact: string;
  readonly kind: 'changed' | 'missing' | 'unexpected';
}

function compareText(left: string, right: string): number {
  return left < right ? -1 : left > right ? 1 : 0;
}

function canonicalValue(value: unknown): unknown {
  if (Array.isArray(value)) return value.map(canonicalValue);
  if (typeof value !== 'object' || value === null) return value;

  return Object.fromEntries(
    Object.keys(value)
      .sort(compareText)
      .map((key) => [key, canonicalValue((value as Record<string, unknown>)[key])]),
  );
}

function canonicalJson(value: unknown): string {
  return `${JSON.stringify(canonicalValue(value), undefined, 2)}\n`;
}

function sha256(value: string): string {
  return createHash('sha256').update(value, 'utf8').digest('hex');
}

function runtimeCatalogSource(catalog: readonly IconRecord[]): string {
  const records = catalog.map(({ id, direction, primitives }) => ({
    name: id,
    direction,
    primitives,
  }));

  return [
    '// Generated by the private Phase 5D-A proof. Do not edit.',
    '// This candidate is not a production package export.',
    '',
    `export const generatedIconCatalog = ${JSON.stringify(records, undefined, 2)} as const;`,
    '',
    "export type GeneratedIconName = (typeof generatedIconCatalog)[number]['name'];",
    '',
  ].join('\n');
}

export function generateIconArtifacts(input: unknown): GeneratedIconArtifacts {
  const catalog = [...validateIconCatalog(input)].sort((left, right) =>
    compareText(left.id, right.id),
  );
  const sourceFingerprint = sha256(canonicalJson(catalog));
  const runtimeCatalog = runtimeCatalogSource(catalog);
  const sourceManifest = canonicalJson({
    catalogSchemaVersion: 1,
    iconCount: catalog.length,
    icons: catalog.map((icon) => ({
      direction: icon.direction,
      fingerprint: sha256(canonicalJson(icon)),
      id: icon.id,
    })),
    sourceFingerprint,
  });
  const outputManifest = canonicalJson({
    artifacts: [
      {
        bytes: Buffer.byteLength(runtimeCatalog),
        name: 'runtime-catalog.ts',
        sha256: sha256(runtimeCatalog),
      },
      {
        bytes: Buffer.byteLength(sourceManifest),
        name: 'source-manifest.json',
        sha256: sha256(sourceManifest),
      },
    ],
    generator: 'phase-5d-icon-tooling',
    generatorSchemaVersion: 1,
    sourceFingerprint,
  });

  return Object.freeze({
    'runtime-catalog.ts': runtimeCatalog,
    'source-manifest.json': sourceManifest,
    'output-manifest.json': outputManifest,
  });
}

export function detectGeneratedArtifactDrift(
  actual: Readonly<Record<string, string>>,
  expected: GeneratedIconArtifacts,
): readonly ArtifactDrift[] {
  const expectedNames = new Set<string>(generatedArtifactNames);
  const drift: ArtifactDrift[] = [];

  for (const artifact of generatedArtifactNames) {
    if (!Object.hasOwn(actual, artifact)) drift.push({ artifact, kind: 'missing' });
    else if (actual[artifact] !== expected[artifact]) drift.push({ artifact, kind: 'changed' });
  }
  for (const artifact of Object.keys(actual).sort(compareText)) {
    if (!expectedNames.has(artifact)) drift.push({ artifact, kind: 'unexpected' });
  }

  return Object.freeze(drift);
}
